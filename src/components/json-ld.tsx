// Structured data for search engines. Escaping "<" keeps a value containing
// "</script>" from closing the tag; the objects are site-authored either way.
export function JsonLd({ data }: { data: Record<string, unknown> }) {
  return (
    <script
      type="application/ld+json"
      dangerouslySetInnerHTML={{
        __html: JSON.stringify(data).replace(/</g, "\\u003c"),
      }}
    />
  );
}
