test("CFB spread, moneyline and total picks reproduce stored probabilities", () => {
  const spread = pickProbabilities(
    { market: "spreads", side: "home", point: -12.5 },
    17.0054281829219,
    17.8240399928454,
    500,
    null,
  );
  close(spread.win, 0.599921877832123);
  assert.equal(spread.push, 0);

  const moneyline = pickProbabilities(
    { market: "h2h", side: "away", point: null },
    24.5301271303596,
    17.8506367042746,
    500,
    null,
  );
  close(moneyline.win, 0.0845727971078069);

  const total = pickProbabilities(
    { market: "totals", side: "over", point: 54.5 },
    58.1329937425437,
    17.7602458040071,
    500,
    null,
  );
  close(total.win, 0.581159720097922);
});

test("stored probability edge equals push-conditional win minus break-even", () => {
  const p = pickProbabilities(
    { market: "spreads", side: "away", point: 7 },
    5.28381824331628,
    13.7082614424095,
    7,
    NFL_WEIGHTS,
  );
  const edge = p.win / (1 - p.push) - breakEvenProbability(-110);
  close(edge, 0.0552464633344051, 5e-6);
  close(breakEvenProbability(172), 100 / 272, 1e-12);
});
